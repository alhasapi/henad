#!/usr/bin/env bash
# Build an Arch Linux pacman package (.pkg.tar.zst) from a Tauri deb bundle.
#
# Tauri has no pacman bundle target, so this reuses the deb payload (binary, desktop
# entry, hicolor icons) and writes a package the Arch way: a zstd tarball with
# .PKGINFO and .MTREE at the top level. Runs unprivileged; needs `bsdtar` and `zstd`.
set -euo pipefail

version="${1:?usage: arch-package.sh <version> [bundle-dir] [out-dir]}"
repo_root="$(cd "$(dirname "$0")/.." && pwd)"
bundle="${2:-$repo_root/src-tauri/target/release/bundle}"
out="${3:-$bundle/arch}"

shopt -s nullglob
debs=("$bundle"/deb/*.deb)
[ "${#debs[@]}" -gt 0 ] || {
  echo "arch-package: no .deb in $bundle/deb (run: npm run tauri build -- --bundles deb)" >&2
  exit 1
}
deb="${debs[0]}"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
mkdir -p "$work/root" "$work/stage" "$out"

bsdtar -xf "$deb" -C "$work"
bsdtar -xf "$work/data.tar.gz" -C "$work/root"

stage="$work/stage"
install -Dm755 "$work/root/usr/bin/henad" "$stage/usr/bin/henad"

# Rename the desktop entry to the binary name and point it at /usr/bin/henad.
mkdir -p "$stage/usr/share/applications"
sed -e 's|^Exec=.*|Exec=henad|' -e 's|^Icon=.*|Icon=henad|' \
  "$work/root/usr/share/applications/Henad.desktop" \
  >"$stage/usr/share/applications/henad.desktop"
chmod 644 "$stage/usr/share/applications/henad.desktop"

# Tauri names the densest icon set "256x256@2"; hicolor expects the real pixel size.
for icon in "$work"/root/usr/share/icons/hicolor/*/apps/*.png; do
  dir="$(basename "$(dirname "$(dirname "$icon")")")"
  [ "$dir" = "256x256@2" ] && dir="512x512"
  install -Dm644 "$icon" "$stage/usr/share/icons/hicolor/$dir/apps/henad.png"
done

installed_size="$(du -sb --apparent-size "$stage" | cut -f1)"
build_date="$(date +%s)"
pkgver="$version-1"

cat >"$stage/.PKGINFO" <<EOF
# Generated by henad's scripts/arch-package.sh
pkgname = henad
pkgbase = henad
pkgver = $pkgver
pkgdesc = Local-network file transfer: discovery, pairing, verified sends
url = https://github.com/alhasapi/henad
builddate = $build_date
packager = Henad contributors
size = $installed_size
arch = x86_64
license = MIT
depend = gtk3
depend = webkit2gtk-4.1
EOF

# .MTREE is what pacman uses for ownership checks; keep root-neutral (no uid/gid).
(
  cd "$stage"
  bsdtar -czf .MTREE --format=mtree \
    --options='!all,use-set,type,mode,time,size,md5,sha256,link' \
    .PKGINFO usr
)

target="$out/henad-$pkgver-x86_64.pkg.tar.zst"
(
  cd "$stage"
  bsdtar -cf - .PKGINFO .MTREE usr | zstd -19 -T0 -q -o "$target"
)
echo "$target"
